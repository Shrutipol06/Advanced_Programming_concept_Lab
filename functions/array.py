#integer array
arr = [10, 20, 30, 40, 50]
print("Integer Array:")
print(arr)
print("\n")

#float array
arr = [10.5, 20.5, 30.5, 40.5]
print("Float Array:")
print(arr)
print("\n")

#double array
arr = [10.123456789, 20.987654321, 30.555555555]
print("Double Array:")
print(arr)
print("\n")

#string array
arr = ["Apple", "Banana", "Mango", "Orange"]
print("String Array:")
print(arr)
print("\n")

#character array
arr = ['A', 'B', 'C', 'D']
print("Character Array:")
print(arr)
print("\n")

#boolean array
arr = [True, False, True, False]
print("Boolean Array:")
print(arr)